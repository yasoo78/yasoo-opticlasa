// Alias so the site-wide "Намери най-близкия" / "contact" CTAs resolve to the contacts page.
STATIC_PAGES['contact'] = STATIC_PAGES['kontakti'];

export function StaticPage({title, eyebrow, intro, blocks, mapQuery}: StaticPageData) {
  return (
    <>
      <article className="mx-auto max-w-5xl py-2">
        {eyebrow && <span className="font-display text-[9px] font-bold uppercase tracking-[0.2em] text-red">{eyebrow}</span>}
        <h1 className="mt-2 font-display text-[clamp(28px,4vw,44px)] font-extrabold uppercase leading-[1.05] tracking-[-0.01em] text-ink">{title}</h1>
        <div className="mt-4 h-[3px] w-12 bg-red" />
        {intro && <p className="mt-7 text-[16px] font-light leading-[1.8] text-ink/80">{intro}</p>}
        <div className="mt-6 flex flex-col gap-5 text-[15px] font-light leading-[1.85] text-mid">
          {blocks.map((b, i) => <BlockView key={i} block={b} />)}
        </div>
      </article>
      {mapQuery && (
        // Full-bleed map, flush with the footer (cancels the inner page's bottom padding).
        <div className="mt-14 -mb-10 ml-[calc(50%-50vw)] w-screen">
          <iframe
            title="Карта"
            src={`https://maps.google.com/maps?q=${encodeURIComponent(mapQuery)}&z=16&output=embed`}
            className="block h-[360px] w-full border-0 md:h-[440px]"
            loading="lazy"
            referrerPolicy="no-referrer-when-downgrade"
          />
        </div>
      )}
    </>
  );
}

function BlockView({block}: {block: Block}) {
  if ('h' in block) return <h2 className="mt-3 font-display text-[16px] font-bold uppercase tracking-[0.04em] text-ink">{block.h}</h2>;
  if ('p' in block) return <p>{block.p}</p>;
  if ('ul' in block) return <ul className="flex list-disc flex-col gap-2 pl-5 marker:text-red">{block.ul.map((x, i) => <li key={i}>{x}</li>)}</ul>;
  if ('ol' in block) return <ol className="flex list-decimal flex-col gap-3 pl-5 marker:font-bold marker:text-red">{block.ol.map((x, i) => <li key={i} className="pl-1">{x}</li>)}</ol>;
  if ('faq' in block) return (
    <div className="flex flex-col divide-y divide-line border-y border-line">
      {block.faq.map((f, i) => (
        <div key={i} className="py-5">
          <h3 className="font-display text-[15px] font-bold text-ink">{f.q}</h3>
          <p className="mt-2 leading-[1.8] text-mid">{f.a}</p>
        </div>
      ))}
    </div>
  );
  if ('callout' in block) return (
    <div className="mt-2 rounded-xl bg-sand px-6 py-5">
      <div className="font-display text-[12px] font-bold uppercase tracking-[0.06em] text-ink">{block.callout.title}</div>
      <div className="mt-2.5 flex flex-col gap-1 text-[14px] leading-[1.7] text-mid">
        {block.callout.lines.map((l, i) => <div key={i}>{l}</div>)}
      </div>
    </div>
  );
  return null;
}
